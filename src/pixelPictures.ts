/**
 * Utility to rotate a 2D string matrix by 90 degrees clockwise
 */
export function rotatePattern90(pattern: string[]): string[] {
  const rows = pattern.length;
  const cols = pattern[0].length;
  const result: string[] = [];

  for (let c = 0; c < cols; c++) {
    let newRow = '';
    for (let r = rows - 1; r >= 0; r--) {
      newRow += pattern[r][c] || '.';
    }
    result.push(newRow);
  }
  return result;
}

/**
 * Utility to mirror a 2D string matrix horizontally
 */
export function mirrorPatternHorizontal(pattern: string[]): string[] {
  return pattern.map((row) => row.split('').reverse().join(''));
}

/**
 * Utility to mirror a 2D string matrix vertically
 */
export function mirrorPatternVertical(pattern: string[]): string[] {
  return [...pattern].reverse();
}
